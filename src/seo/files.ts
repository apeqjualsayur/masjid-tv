// robots.txt, sitemap.xml and llms.txt (_specs/70-PRD-seo.md §3.B), generated at build time from the page
// registry (scripts/build-seo.ts writes them to public/, git-ignored). Pure: strings in, strings out.
import { articlePath, publishedArticles, type Article } from "@/content/artikel";
import { copy, t, type Lang } from "@/landing/i18n";
import { pageText } from "./metadata";
import { PAGES, languageVersions, type SeoPage } from "./routes";
import { FEED_PATH, SITE } from "./site";

const abs = (path: string) => SITE.url + path;
const GENERATED = "Generated by scripts/build-seo.ts from src/seo (do not edit by hand).";

/** Never crawled: the TV display, the admin app and the APK download. */
export const DISALLOW = ["/admin", "/tv", "/apk"] as const;

/**
 * Search and AI crawlers that get their own explicit group (PRD §3.B). A crawler with its own group
 * ignores the `*` group, so each group repeats the Disallow lines.
 */
export const NAMED_BOTS = ["OAI-SearchBot", "ChatGPT-User", "GPTBot", "PerplexityBot", "ClaudeBot", "Claude-SearchBot", "Google-Extended", "Bingbot"] as const;

export function robotsTxt(): string {
  const group = (agent: string) => [`User-agent: ${agent}`, "Allow: /", ...DISALLOW.map((d) => `Disallow: ${d}`)].join("\n");
  return [`# ${new URL(SITE.url).host} — ${GENERATED}`, group("*"), ...NAMED_BOTS.map(group), `Sitemap: ${abs("/sitemap.xml")}`].join("\n\n") + "\n";
}

const xml = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** Every registered page with lastmod (its content date) and hreflang alternates for pairs. */
export function sitemapXml(pages: readonly SeoPage[] = PAGES): string {
  const urls = pages.map((p) => {
    const lines = [`    <loc>${xml(abs(p.path))}</loc>`, `    <lastmod>${p.updated}</lastmod>`];
    if (p.pair) {
      const v = languageVersions(p);
      for (const [lang, href] of [["ms", v.ms!], ["en", v.en!], ["x-default", v.ms!]] as const) {
        lines.push(`    <xhtml:link rel="alternate" hreflang="${lang}" href="${xml(abs(href))}"/>`);
      }
    }
    return `  <url>\n${lines.join("\n")}\n  </url>`;
  });
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    `<!-- ${GENERATED} -->`,
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">',
    ...urls,
    "</urlset>",
    "",
  ].join("\n");
}

/**
 * S5 adds the "Apakah Masjid View?" text (whatIs.body). Until then llms.txt uses each language's meta
 * description; S5 sets this to true, and from then on an empty whatIs.body fails the build.
 */
export const LLMS_REQUIRE_WHAT_IS = true;

/** The "what is Masjid View" paragraph for one language. */
export function whatIs(lang: Lang, requireWhatIs = LLMS_REQUIRE_WHAT_IS): string {
  const body = copy(lang).whatIs.body.trim();
  if (body) return body;
  if (requireWhatIs) throw new Error(`llms.txt: whatIs.body is empty in src/landing/i18n/${lang}.json (the "Apakah Masjid View?" text)`);
  return t(lang, "meta.description");
}

const linkLine = (p: SeoPage) => {
  const { title, description } = pageText(p);
  return `- [${title}](${abs(p.path)}): ${description}`;
};

/** llms.txt (llmstxt.org): title, one-line summary, BM then EN paragraph, then link lists. */
export function llmsTxt(pages: readonly SeoPage[] = PAGES, requireWhatIs = LLMS_REQUIRE_WHAT_IS): string {
  const main = pages.filter((p) => p.type !== "article");
  const articles = pages.filter((p) => p.type === "article");
  const parts = [
    `# ${SITE.brand}`,
    `> ${t("en", "seo.summary")}`,
    whatIs("ms", requireWhatIs),
    whatIs("en", requireWhatIs),
    `## Halaman utama\n\n${main.map(linkLine).join("\n")}`,
  ];
  // The article list appears once the first article is published (S8/S9).
  if (articles.length) parts.push(`## Artikel\n\n${articles.map(linkLine).join("\n")}`);
  return parts.join("\n\n") + "\n";
}

/** RFC 822 date for RSS, at midnight Malaysia time of a YYYY-MM-DD date (stable: no build clock). */
export function rfc822(iso: string): string {
  const [y, m, d] = iso.split("-").map(Number);
  const day = new Date(Date.UTC(y, m - 1, d)).toUTCString().slice(0, 16); // "Mon, 08 Feb 2027"
  return `${day} 00:00:00 +0800`;
}

/** RSS 2.0 feed of the published articles, newest first (/artikel/feed.xml). Empty channel when none. */
export function rssXml(articles: readonly Article[] = publishedArticles()): string {
  const hub = { title: `${SITE.brand} · ${t("ms", "artikel.title")}`, link: abs("/artikel/"), description: t("ms", "artikel.meta.description") };
  const newest = articles.map((a) => a.dateModified).sort().at(-1);
  const items = articles.map((a) =>
    [
      "    <item>",
      `      <title>${xml(a.title)}</title>`,
      `      <link>${xml(abs(articlePath(a.slug)))}</link>`,
      `      <guid isPermaLink="true">${xml(abs(articlePath(a.slug)))}</guid>`,
      `      <pubDate>${rfc822(a.datePublished)}</pubDate>`,
      `      <description>${xml(a.summary)}</description>`,
      "    </item>",
    ].join("\n"),
  );
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    `<!-- ${GENERATED} -->`,
    '<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">',
    "  <channel>",
    `    <title>${xml(hub.title)}</title>`,
    `    <link>${xml(hub.link)}</link>`,
    `    <description>${xml(hub.description)}</description>`,
    "    <language>ms</language>",
    `    <atom:link href="${xml(abs(FEED_PATH))}" rel="self" type="application/rss+xml"/>`,
    ...(newest ? [`    <lastBuildDate>${rfc822(newest)}</lastBuildDate>`] : []),
    ...items,
    "  </channel>",
    "</rss>",
    "",
  ].join("\n");
}
