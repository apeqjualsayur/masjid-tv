// Copies the usage model into the Edge Functions folder for the usage-digest alert job (PRD usage §6):
//   src/admin/usage/model.ts → supabase/functions/_shared/usage-model.ts
//   src/admin/usage/types.ts → supabase/functions/_shared/usage-types.ts
//   npm run sync:usage-model
// scripts/sync-usage-model.test.ts fails when the copies are stale.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

export const HEADER = "// generated by npm run sync:usage-model — edit src/admin/usage/*";
const ROOT = join(import.meta.dirname, "..");
export const COPIES = [
  { from: "src/admin/usage/model.ts", to: "supabase/functions/_shared/usage-model.ts" },
  { from: "src/admin/usage/types.ts", to: "supabase/functions/_shared/usage-types.ts" },
] as const;

/** The text the copy must have: header line + source, with Deno-style import paths. */
export function sharedCopy(source: string): string {
  return `${HEADER}\n${source.replace(/from "\.\/types"/g, 'from "./usage-types.ts"')}`;
}

export function expected(): { path: string; text: string }[] {
  return COPIES.map((c) => ({ path: join(ROOT, c.to), text: sharedCopy(readFileSync(join(ROOT, c.from), "utf8")) }));
}

if (process.argv[1] && /sync-usage-model\.ts$/.test(process.argv[1])) {
  mkdirSync(join(ROOT, "supabase/functions/_shared"), { recursive: true });
  for (const f of expected()) {
    writeFileSync(f.path, f.text);
    console.log(`wrote ${f.path.slice(ROOT.length + 1).replace(/\\/g, "/")}`);
  }
}
